    FROM pumpdotfun_solana.pump_amm_evt_createpoolevent c
    JOIN coins k ON k.mint = c.base_mint
    WHERE c.evt_block_date BETWEEN DATE '2026-08-12' AND DATE '2026-08-12'
      AND c.evt_outer_executing_account = '6EF8rrecthR5Dkzon8Nwu78hRvfCKubJ14M5uBEwF6P'
