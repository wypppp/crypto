       W 的币再截到截点：选集只用截点之前的成交与事件 */
    SELECT k.mint, k.created_at, k.n_create, k.created_at < TIMESTAMP '2026-08-17 00:00:00' AS is_w,
           least(k.created_at + INTERVAL '30' DAY, TIMESTAMP '2026-10-05 00:00:00', TIMESTAMP '2026-09-23 00:00:00',
                 IF(k.created_at < TIMESTAMP '2026-08-17 00:00:00', TIMESTAMP '2026-08-17 00:00:00', TIMESTAMP '2026-09-23 00:00:00')) AS obs_end
    FROM coins k
    WHERE k.created_at >= TIMESTAMP '2026-08-10 00:00:00' AND k.created_at < TIMESTAMP '2026-08-24 00:00:00'
