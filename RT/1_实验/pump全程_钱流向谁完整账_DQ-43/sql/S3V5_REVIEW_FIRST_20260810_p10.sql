    SELECT t.mint, c.is_w, c.obs_end, t.evt_block_time AS ts, t.evt_block_slot AS slot, t.evt_tx_index AS txi,
           t.evt_outer_instruction_index AS oix, COALESCE(t.evt_inner_instruction_index, -1) AS iix,
