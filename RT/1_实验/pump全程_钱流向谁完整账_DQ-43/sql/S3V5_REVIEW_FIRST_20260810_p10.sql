    SELECT x.*,
           sum(sg) OVER (PARTITION BY mint ORDER BY slot, txi, oix, iix, tx_id ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING) AS cum_x,
           sum(sg) OVER (PARTITION BY mint ORDER BY ts RANGE BETWEEN UNBOUNDED PRECEDING AND INTERVAL '60' SECOND PRECEDING) AS cum_60
    FROM (SELECT tr.*, IF(is_buy, amt, -amt) AS sg FROM tr) x
),
ar AS (
    SELECT p.mint,CAST(a."user" AS varchar) AS usr,a.evt_block_time AS ts,a.evt_block_slot AS slot,
