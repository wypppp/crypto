           min_by(symbol,ARRAY[evt_block_slot,evt_tx_index,evt_outer_instruction_index,COALESCE(evt_inner_instruction_index,-1)]) AS symbol,
           min_by(COALESCE(creator,"user"),ARRAY[evt_block_slot,evt_tx_index,evt_outer_instruction_index,COALESCE(evt_inner_instruction_index,-1)]) AS creator,
           min_by(quote_mint,ARRAY[evt_block_slot,evt_tx_index,evt_outer_instruction_index,COALESCE(evt_inner_instruction_index,-1)]) AS quote_mint
    FROM pumpdotfun_solana.pump_evt_createevent
