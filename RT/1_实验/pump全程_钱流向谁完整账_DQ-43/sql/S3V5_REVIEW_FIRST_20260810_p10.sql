           max(c.quote_mint) AS quote_mint,count(*) AS n_cp
    FROM pumpdotfun_solana.pump_amm_evt_createpoolevent c JOIN coins k ON k.mint=c.base_mint
    WHERE c.evt_block_date BETWEEN DATE '2026-08-10' AND DATE '2026-09-22'
      AND c.evt_outer_executing_account='6EF8rrecthR5Dkzon8Nwu78hRvfCKubJ14M5uBEwF6P' AND c.index=0
      AND c.evt_block_time >= k.created_at AND c.evt_block_time < k.created_at+INTERVAL '30' DAY
