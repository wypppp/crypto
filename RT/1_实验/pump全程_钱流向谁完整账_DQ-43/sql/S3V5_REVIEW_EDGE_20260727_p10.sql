    FROM s_keep WHERE from_seed AND to_seed
    UNION ALL
    SELECT 'G', NULL, k.from_owner, k.to_owner, k.n, CAST(k.amt AS varchar), date_diff('second',TIMESTAMP '1970-01-01 00:00:00',k.t0),
           date_diff('second',TIMESTAMP '1970-01-01 00:00:00',k.t1), f.fanout, k.n_first_of, 1
    FROM s_keep k LEFT JOIN f_fan f ON f.from_owner = k.from_owner
    WHERE k.r_in = 1 AND k.n_first_of >= 2
    UNION ALL
