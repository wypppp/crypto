ev AS (
    SELECT e.pool, e.ts, e.slot, e.txi, e.oix, COALESCE(e.iix0, -1) AS iix, e.tx_id, e.side, e.usr,
           e.q0, e.b0, e.q_pool, e.b_amt, e.q_user, e.f_lp, e.f_pr, e.f_cr, e.q_gross_out,
           CASE WHEN e.side = 'S' THEN e.f_cb0 ELSE r.cb END AS f_cb,
           CASE WHEN e.side = 'S' THEN e.f_bb0 ELSE r.bb END AS f_bb,
           CASE WHEN e.ts < TIMESTAMP '2026-07-15 00:00:00' THEN CAST(0 AS DECIMAL(38,0)) ELSE r.vq END AS vq, CASE WHEN e.ts < TIMESTAMP '2026-07-15 00:00:00' THEN 'layout0_date' WHEN r.tx_id IS NULL THEN 'missing' ELSE r.layout END AS vq_src, COALESCE(r.vq_ovf, 0) AS vq_ovf
    FROM ev0 e
    LEFT JOIN rv r ON r.tx_id = e.tx_id AND r.oix = e.oix AND r.iix = e.iix0 AND r.kind = e.side
