       count_if(signer_is_user AND keys_aligned AND CAST(res_v1 AS DECIMAL(38,0)) <> 0
                AND CAST(res_v1 AS DECIMAL(38,0)) = -CAST(d_other_pos AS DECIMAL(38,0))) AS n_res_v1_eq_minus_other_inflow,
       count_if(signer_is_user AND keys_aligned AND CAST(res_v1 AS DECIMAL(38,0)) < 0
                AND CAST(d_other_pos AS DECIMAL(38,0)) > 0) AS n_res_v1_neg_with_other_inflow,
       count_if(CAST(d_all AS DECIMAL(38,0)) + CAST(fee AS DECIMAL(38,0)) <> 0) AS n_lamports_not_conserved_after_fee,
       sum(length(concat_ws(',', CAST(chain AS varchar), CAST(tx_id AS varchar), CAST(ts AS varchar), CAST(slot AS varchar), CAST(txi AS varchar), CAST(signer AS varchar), CAST(success AS varchar), CAST(fee AS varchar), CAST(priority_fee AS varchar), CAST(required_signatures AS varchar), CAST(compute_units_consumed AS varchar), CAST(cu_limit AS varchar), CAST(n_legs AS varchar), CAST(n_users AS varchar), CAST(n_curve AS varchar), CAST(n_amm AS varchar), CAST(signer_is_user AS varchar), CAST(cash_v1 AS varchar), CAST(cash_v2 AS varchar), CAST(cash_v3 AS varchar), CAST(d_trader AS varchar), CAST(tip_jito AS varchar), CAST(d_fee_recip AS varchar), CAST(d_other AS varchar), CAST(d_all AS varchar), CAST(d_other_pos AS varchar), CAST(d_pool AS varchar), CAST(keys_aligned AS varchar), CAST(n_key AS varchar), CAST(res_v1 AS varchar), CAST(res_v2 AS varchar), CAST(res_v3 AS varchar)))) + count(*) * 32 AS est_csv_bytes
       /* 资金路径表在 10-13 第一次抽样冒烟里已出；本版不再二次引用 cls（会重扫交易表） */
FROM out
