),
c1 AS (
    SELECT c0.*,
           CASE WHEN symbol IS NULL OR trim(replace(symbol, '$', '')) = '' THEN 'excl'
                WHEN upper(trim(replace(symbol, '$', ''))) IN (SELECT base FROM excl) THEN 'excl'
                WHEN quote_mint IS NOT NULL AND quote_mint <> '11111111111111111111111111111111' THEN 'excl'
                ELSE 'in' END AS pop_class
    FROM c0
    WHERE created_at >= TIMESTAMP '2026-08-12 00:00:00' AND created_at < TIMESTAMP '2026-08-12 00:00:00' + INTERVAL '1' DAY
      AND created_at < TIMESTAMP '2026-10-05 00:00:00'
