pop AS (SELECT * FROM c1 WHERE pop_class = 'in'),
coins AS (SELECT * FROM pop
    WHERE mod(bitwise_and(from_big_endian_64(substr(sha256(to_utf8('RT-DQ43-coin-sample-v1|' || mint)), 1, 8)), 9223372036854775807), 10000) < 1000),
comp AS (
    /* 10-14（GPT 01）：聚合前 JOIN coins，逐币限 created_at ≤ 事件 < created_at＋30 天，并保留全局止日 */
    SELECT e.mint, to_unixtime(min(e.evt_block_time)) AS completed_t, count(*) AS n_complete,
           /* 10-14（汇总版）：毕业事件的键、交易与触发者，A 的命中与自身触发要用 */
           min_by(e.evt_block_slot, e.evt_block_time) AS comp_slot, min_by(e.evt_tx_index, e.evt_block_time) AS comp_txi,
           min_by(e.evt_outer_instruction_index, e.evt_block_time) AS comp_oix,
           min_by(COALESCE(e.evt_inner_instruction_index, -1), e.evt_block_time) AS comp_iix,
           min_by(e.evt_tx_id, e.evt_block_time) AS comp_tx, min_by(CAST(e."user" AS varchar), e.evt_block_time) AS comp_user
    FROM pumpdotfun_solana.pump_evt_completeevent e
    JOIN coins k ON k.mint = e.mint
    WHERE e.evt_block_date BETWEEN DATE '2026-08-12' AND DATE '2026-08-12'
      AND e.evt_block_time >= k.created_at AND e.evt_block_time < k.created_at + INTERVAL '30' DAY
      AND e.evt_block_time < TIMESTAMP '2026-10-05 00:00:00'
    GROUP BY 1
),
mig AS (
    SELECT e.mint, to_unixtime(min(e.evt_block_time)) AS migrated_t, min_by(e.pool, e.evt_block_time) AS pool, count(*) AS n_mig
    FROM pumpdotfun_solana.pump_evt_completepumpammmigrationevent e
    JOIN coins k ON k.mint = e.mint
    WHERE e.evt_block_date BETWEEN DATE '2026-08-12' AND DATE '2026-08-12'
      AND e.evt_block_time >= k.created_at AND e.evt_block_time < k.created_at + INTERVAL '30' DAY
      AND e.evt_block_time < TIMESTAMP '2026-10-05 00:00:00'
    GROUP BY 1
),
out AS (
    SELECT 'solana' AS chain, k.mint, to_unixtime(k.created_at) AS created_t, k.n_create, k.name, k.symbol, k.uri, k.creator,
           k.create_user, k.create_signer, k.create_tx, k.c_slot, k.c_txi, k.c_oix, k.c_iix, k.bonding_curve, k.token_program,
           k.is_mayhem_mode, k.is_cashback_enabled, k.quote_mint,
           CAST(k.vsr0 AS varchar) AS vsr0, CAST(k.vtr0 AS varchar) AS vtr0, CAST(k.rtr0 AS varchar) AS rtr0,
           CAST(k.vqr0 AS varchar) AS vqr0, CAST(k.supply AS varchar) AS supply,
           cp.completed_t, cp.n_complete, cp.comp_slot, cp.comp_txi, cp.comp_oix, cp.comp_iix, cp.comp_tx, cp.comp_user,
           mg.migrated_t, mg.pool, mg.n_mig,
           k.created_at + INTERVAL '30' DAY <= TIMESTAMP '2026-10-05 00:00:00' AS window_complete,
           count(*) OVER (PARTITION BY k.mint) AS n_key
    FROM coins k
    LEFT JOIN comp cp ON cp.mint = k.mint
    LEFT JOIN mig mg ON mg.mint = k.mint
)
SELECT 'COIN' AS layer, count(*) AS n_rows, count_if(n_key > 1) AS n_dup_key, count_if(creator IS NULL) AS null_creator, count_if(symbol IS NULL) AS null_symbol, count_if(quote_mint IS NULL) AS null_quote_mint, count_if(bonding_curve IS NULL) AS null_bonding_curve, count_if(token_program IS NULL) AS null_token_program, count_if(supply IS NULL) AS null_supply, count(DISTINCT mint) AS n_coins, count_if(completed_t IS NOT NULL) AS n_completed, count_if(pool IS NOT NULL) AS n_migrated, count_if(is_mayhem_mode) AS n_mayhem, count_if(n_create > 1) AS n_multi_create,
       (SELECT count(*) FROM c1 WHERE pop_class <> 'in') AS n_excluded,
       (SELECT count(DISTINCT mint) FROM pumpdotfun_solana.pump_evt_createevent
         WHERE evt_block_date BETWEEN DATE '2026-08-12' AND DATE '2026-08-12'
           AND evt_block_time >= TIMESTAMP '2026-08-12 00:00:00' AND evt_block_time < TIMESTAMP '2026-08-12 00:00:00' + INTERVAL '1' DAY)
