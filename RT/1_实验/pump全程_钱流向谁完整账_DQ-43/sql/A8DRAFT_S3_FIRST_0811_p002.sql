cw AS (
    /* 窗口币：is_w＝W 的币（创建早于截点 2026-08-12 00:00:00）。观察终点＝min(创建＋30 天, 止日, 数据止点 2026-08-13 00:00:00)，
       W 的币再截到截点：选集只用截点之前的成交与事件 */
    SELECT k.mint, k.created_at, k.created_at < TIMESTAMP '2026-08-12 00:00:00' AS is_w,
           least(k.created_at + INTERVAL '30' DAY, TIMESTAMP '2026-10-05 00:00:00', TIMESTAMP '2026-08-13 00:00:00',
                 IF(k.created_at < TIMESTAMP '2026-08-12 00:00:00', TIMESTAMP '2026-08-12 00:00:00', TIMESTAMP '2026-08-13 00:00:00')) AS obs_end
    FROM coins k
