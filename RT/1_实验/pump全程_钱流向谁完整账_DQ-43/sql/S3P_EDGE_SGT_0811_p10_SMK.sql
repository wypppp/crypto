s_edges AS (
    /* 一端是种子的 SOL 边（≥0.05），在截点之前先过滤、再按地址对汇总（10-14，GPT 04）。只在本 CTE 内部用，不整体导出 */
    SELECT from_owner, to_owner, count(*) AS n, sum(amt) AS amt, min(block_time) AS t0, max(block_time) AS t1,
           from_owner IN (SELECT usr FROM seed) AS from_seed, to_owner IN (SELECT usr FROM seed) AS to_seed
    FROM nat
    WHERE from_owner IN (SELECT usr FROM seed) OR to_owner IN (SELECT usr FROM seed)
    GROUP BY 1, 2
),
s2 AS (
    /* 10-14 EDGE v3（取数附录 v3 §4）：只导出能把两个种子连起来的边（DQ-26 的三类）。
       第一笔资金来源＝种子在窗口内最早的入账地址对（按首次时刻、再按地址定序） */
    SELECT s.*,
           CASE WHEN s.to_seed THEN row_number() OVER (PARTITION BY s.to_owner ORDER BY s.t0, s.from_owner) END AS r_in
    FROM s_edges s
),
s3 AS (
    SELECT s2.*, count_if(r_in = 1) OVER (PARTITION BY from_owner) AS n_first_of
    FROM s2
),
s_keep AS (
    /* S＝两端都是种子的边；G＝种子的第一笔来源，且这个来源是至少两个种子的第一笔来源 */
    SELECT * FROM s3 WHERE (from_seed AND to_seed) OR (r_in = 1 AND n_first_of >= 2)
),
f_fan AS (
    /* 共同第一笔来源的扇出（不同接收方数，全部接收方，不只种子；>200 视为服务节点）。
       交易所等大来源接收方很多，用 approx_distinct（标准误约 2%，只用来和 200 比） */
    SELECT n.from_owner, approx_distinct(n.to_owner) AS fanout
    FROM nat n
    WHERE n.from_owner IN (SELECT from_owner FROM s_keep WHERE r_in = 1 AND n_first_of >= 2)
    GROUP BY 1
),
c_edges AS (
    /* C：创建者关联体——每个币创建前 7 天内与创建者的直接 SOL 往来，逐币窗口先过滤再汇总（不设 0.05 下限）。
       10-14：原写法按“付款方或收款方是创建者”的 OR 连接，Trino 无法哈希连接，冒烟 12 分钟扣 1,087.6 credits；
       改为两条等值连接再合并（付款方与收款方不同，同一条转账不会在两边同一个币下重复）。cp＝创建者的对手 */
    SELECT mint, from_owner, to_owner, cp, count(*) AS n, sum(amount_display) AS amt,
           min(block_time) AS t0, max(block_time) AS t1
    FROM (
        SELECT k.mint, x.from_owner, x.to_owner, x.to_owner AS cp, x.amount_display, x.block_time
        FROM tokens_solana.transfers x
        JOIN kc k ON x.from_owner = k.creator
        WHERE x.block_date BETWEEN DATE '2026-08-04' AND DATE '2026-08-11'
          AND x.block_time >= k.created_at - INTERVAL '7' DAY AND x.block_time < k.created_at
          AND x.token_version = 'native' AND x.action = 'transfer'
          AND x.outer_executing_account = '11111111111111111111111111111111' AND x.from_owner <> x.to_owner
        UNION ALL
        SELECT k.mint, x.from_owner, x.to_owner, x.from_owner, x.amount_display, x.block_time
        FROM tokens_solana.transfers x
        JOIN kc k ON x.to_owner = k.creator
        WHERE x.block_date BETWEEN DATE '2026-08-04' AND DATE '2026-08-11'
          AND x.block_time >= k.created_at - INTERVAL '7' DAY AND x.block_time < k.created_at
          AND x.token_version = 'native' AND x.action = 'transfer'
          AND x.outer_executing_account = '11111111111111111111111111111111' AND x.from_owner <> x.to_owner
    )
    GROUP BY 1, 2, 3, 4
),
t_edges AS (
    /* T：母体币的直接代币转移（不含成交腿），逐币窗口内，截点之前 */
    SELECT x.token_mint_address AS mint, x.from_owner, x.to_owner, count(*) AS n, sum(x.amount_display) AS amt,
           min(x.block_time) AS t0, max(x.block_time) AS t1
    FROM tokens_solana.transfers x
    JOIN kc k ON k.mint = x.token_mint_address
    WHERE x.block_date BETWEEN DATE '2026-08-11' AND DATE '2026-08-11'
      AND x.block_time >= k.created_at AND x.block_time < k.created_at + INTERVAL '30' DAY
      AND x.block_time < TIMESTAMP '2026-08-12 00:00:00' AND x.block_time < TIMESTAMP '2026-10-05 00:00:00'
      AND x.token_version <> 'native' AND x.action = 'transfer'
      AND x.outer_executing_account IN ('TokenkegQfeZyiNwAJbNbGKPFXCWuBvf9Ss623VQ5DA', 'TokenzQdBNbLqP5VEhdkAS6EPFLC1PHnBqCXEpPxuEb', 'ATokenGPvbdGVxr1b2hvZbsiqW5xWH25efTNsLJA8knL')
      AND x.from_owner <> x.to_owner
    GROUP BY 1, 2, 3
),
c_keep AS (
    /* 只留对手是种子、或是本币代币转出方（关联体的一跳）的 C 边；x＝该币创建者在窗口内的对手数（近似，>200 视为服务节点） */
    SELECT c.*, approx_distinct(c.cp) OVER (PARTITION BY c.mint) AS n_cp
    FROM c_edges c
),
out AS (
    SELECT 'S' AS kind, CAST(NULL AS varchar) AS mint, from_owner AS a, to_owner AS b, n, CAST(amt AS varchar) AS amt,
           CAST(to_unixtime(t0) AS bigint) AS first_t, CAST(to_unixtime(t1) AS bigint) AS last_t,
           CAST(NULL AS BIGINT) AS x, CAST(NULL AS BIGINT) AS y, 1 AS n_key
    FROM s_keep WHERE from_seed AND to_seed
    UNION ALL
    SELECT 'G', NULL, k.from_owner, k.to_owner, k.n, CAST(k.amt AS varchar), CAST(to_unixtime(k.t0) AS bigint),
           CAST(to_unixtime(k.t1) AS bigint), f.fanout, k.n_first_of, 1
    FROM s_keep k LEFT JOIN f_fan f ON f.from_owner = k.from_owner
    WHERE k.r_in = 1 AND k.n_first_of >= 2
    UNION ALL
    SELECT 'T' AS kind, mint, from_owner AS a, to_owner AS b, n, CAST(amt AS varchar) AS amt,
           CAST(to_unixtime(t0) AS bigint) AS first_t, CAST(to_unixtime(t1) AS bigint) AS last_t,
           CAST(NULL AS BIGINT) AS x, CAST(NULL AS BIGINT) AS y, 1 AS n_key
    FROM t_edges
)
SELECT 'EDGE' AS layer, count(*) AS n_rows, count_if(n_key > 1) AS n_dup_key, count_if(a IS NULL) AS null_a, count_if(b IS NULL) AS null_b, count_if(kind = 'S') AS n_seed_edges, count_if(kind = 'G') AS n_first_funder_links, count(DISTINCT IF(kind = 'G', a)) AS n_shared_funders, count_if(kind = 'G' AND x > 200) AS n_service_funders, count_if(kind = 'G' AND x IS NULL) AS n_fanout_missing, count_if(kind = 'C') AS n_creator_edges, count_if(kind = 'C' AND x > 200) AS n_creator_service_rows, count_if(kind = 'T') AS n_tok_edges, sum(n) AS n_transfers,
       count(*) AS ck_rows,
       sum(CAST(bitwise_and(from_big_endian_64(xxhash64(to_utf8(concat_ws('|', COALESCE(CAST(kind AS varchar), '~'), COALESCE(CAST(mint AS varchar), '~'), COALESCE(CAST(a AS varchar), '~'), COALESCE(CAST(b AS varchar), '~'), COALESCE(CAST(n AS varchar), '~'), COALESCE(CAST(amt AS varchar), '~'), COALESCE(CAST(first_t AS varchar), '~'), COALESCE(CAST(last_t AS varchar), '~'), COALESCE(CAST(x AS varchar), '~'), COALESCE(CAST(y AS varchar), '~'), COALESCE(CAST(n_key AS varchar), '~'))))), 9223372036854775807) AS DECIMAL(38,0))) AS ck_sum,
       bitwise_xor_agg(from_big_endian_64(xxhash64(to_utf8(concat_ws('|', COALESCE(CAST(kind AS varchar), '~'), COALESCE(CAST(mint AS varchar), '~'), COALESCE(CAST(a AS varchar), '~'), COALESCE(CAST(b AS varchar), '~'), COALESCE(CAST(n AS varchar), '~'), COALESCE(CAST(amt AS varchar), '~'), COALESCE(CAST(first_t AS varchar), '~'), COALESCE(CAST(last_t AS varchar), '~'), COALESCE(CAST(x AS varchar), '~'), COALESCE(CAST(y AS varchar), '~'), COALESCE(CAST(n_key AS varchar), '~')))))) AS ck_xor,
       sum(length(concat_ws(',', CAST(kind AS varchar), CAST(mint AS varchar), CAST(a AS varchar), CAST(b AS varchar), CAST(n AS varchar), CAST(amt AS varchar), CAST(first_t AS varchar), CAST(last_t AS varchar), CAST(x AS varchar), CAST(y AS varchar), CAST(n_key AS varchar)))) + count(*) * 11 AS est_csv_bytes
FROM out
