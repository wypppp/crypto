    SELECT from_owner, to_owner, count(*) AS n, sum(amt) AS amt, min(block_time) AS t0, max(block_time) AS t1,
           min_by(tx_id, block_time) AS tx0
    FROM nat
    WHERE from_owner IN (SELECT usr FROM seed) OR to_owner IN (SELECT usr FROM seed)
    GROUP BY 1, 2
),
f_fan AS (
    /* F：向种子转过钱、自己不是种子的来源地址，在同一窗口内的扇出（不同接收方数；>200 视为服务节点） */
    SELECT n.from_owner, count(DISTINCT n.to_owner) AS fanout
    FROM nat n
    WHERE n.from_owner IN (SELECT from_owner FROM s_edges WHERE to_owner IN (SELECT usr FROM seed))
      AND n.from_owner NOT IN (SELECT usr FROM seed)
    GROUP BY 1
),
c_edges AS (
    /* C：创建者关联体——每个币创建前 7 天内与创建者的直接 SOL 往来，逐币窗口先过滤再汇总（不设 0.05 下限） */
    SELECT k.mint, x.from_owner, x.to_owner, count(*) AS n, sum(x.amount_display) AS amt,
           min(x.block_time) AS t0, max(x.block_time) AS t1, min_by(x.tx_id, x.block_time) AS tx0
    FROM tokens_solana.transfers x
    JOIN kc k ON (x.from_owner = k.creator OR x.to_owner = k.creator)
    WHERE x.block_date BETWEEN DATE '2026-08-05' AND DATE '2026-08-12'
      AND x.block_time >= k.created_at - INTERVAL '7' DAY AND x.block_time < k.created_at
      AND x.token_version = 'native' AND x.action = 'transfer'
      AND x.outer_executing_account = '11111111111111111111111111111111' AND x.from_owner <> x.to_owner
    GROUP BY 1, 2, 3
),
t_edges AS (
    /* T：母体币的直接代币转移（不含成交腿），逐币窗口内，截点之前 */
    SELECT x.token_mint_address AS mint, x.from_owner, x.to_owner, count(*) AS n, sum(x.amount_display) AS amt,
           min(x.block_time) AS t0, max(x.block_time) AS t1, min_by(x.tx_id, x.block_time) AS tx0
    FROM tokens_solana.transfers x
    JOIN kc k ON k.mint = x.token_mint_address
    WHERE x.block_date BETWEEN DATE '2026-08-12' AND DATE '2026-08-12'
      AND x.block_time >= k.created_at AND x.block_time < k.created_at + INTERVAL '30' DAY
      AND x.block_time < TIMESTAMP '2026-08-13 00:00:00' AND x.block_time < TIMESTAMP '2026-10-05 00:00:00'
      AND x.token_version <> 'native' AND x.action = 'transfer'
      AND x.outer_executing_account IN ('TokenkegQfeZyiNwAJbNbGKPFXCWuBvf9Ss623VQ5DA', 'TokenzQdBNbLqP5VEhdkAS6EPFLC1PHnBqCXEpPxuEb', 'ATokenGPvbdGVxr1b2hvZbsiqW5xWH25efTNsLJA8knL')
      AND x.from_owner <> x.to_owner
    GROUP BY 1, 2, 3
),
out AS (
    SELECT 'solana' AS chain, 'S' AS kind, CAST(NULL AS varchar) AS mint, from_owner, to_owner, n, CAST(amt AS varchar) AS amt,
           to_unixtime(t0) AS first_t, to_unixtime(t1) AS last_t, tx0 AS first_tx, CAST(NULL AS BIGINT) AS fanout,
           '2026-08-05 00:00:00' AS win_from, '2026-08-13 00:00:00' AS win_cut, 1 AS n_key
    FROM s_edges
    UNION ALL
    SELECT 'solana', 'F', NULL, from_owner, NULL, NULL, NULL, NULL, NULL, NULL, fanout, '2026-08-05 00:00:00', '2026-08-13 00:00:00', 1 FROM f_fan
    UNION ALL
    SELECT 'solana', 'C', mint, from_owner, to_owner, n, CAST(amt AS varchar), to_unixtime(t0), to_unixtime(t1), tx0, NULL,
           'created-7d', 'created', 1
    FROM c_edges
    UNION ALL
    SELECT 'solana', 'T', mint, from_owner, to_owner, n, CAST(amt AS varchar), to_unixtime(t0), to_unixtime(t1), tx0, NULL,
           'created', '2026-08-13 00:00:00', 1
    FROM t_edges
)
SELECT 'EDGE' AS layer, count(*) AS n_rows, count_if(n_key > 1) AS n_dup_key, count_if(from_owner IS NULL) AS null_from_owner, count_if(kind = 'S') AS n_sol_edges, count_if(kind = 'F') AS n_funders, count_if(kind = 'F' AND fanout > 200) AS n_service, count_if(kind = 'C') AS n_creator_edges, count_if(kind = 'T') AS n_tok_edges, sum(n) AS n_transfers,
       count(*) AS ck_rows,
       sum(CAST(bitwise_and(from_big_endian_64(xxhash64(to_utf8(concat_ws('|', COALESCE(CAST(chain AS varchar), '~'), COALESCE(CAST(kind AS varchar), '~'), COALESCE(CAST(mint AS varchar), '~'), COALESCE(CAST(from_owner AS varchar), '~'), COALESCE(CAST(to_owner AS varchar), '~'), COALESCE(CAST(n AS varchar), '~'), COALESCE(CAST(amt AS varchar), '~'), COALESCE(CAST(first_t AS varchar), '~'), COALESCE(CAST(last_t AS varchar), '~'), COALESCE(CAST(first_tx AS varchar), '~'), COALESCE(CAST(fanout AS varchar), '~'), COALESCE(CAST(win_from AS varchar), '~'), COALESCE(CAST(win_cut AS varchar), '~'), COALESCE(CAST(n_key AS varchar), '~'))))), 9223372036854775807) AS DECIMAL(38,0))) AS ck_sum,
       bitwise_xor_agg(from_big_endian_64(xxhash64(to_utf8(concat_ws('|', COALESCE(CAST(chain AS varchar), '~'), COALESCE(CAST(kind AS varchar), '~'), COALESCE(CAST(mint AS varchar), '~'), COALESCE(CAST(from_owner AS varchar), '~'), COALESCE(CAST(to_owner AS varchar), '~'), COALESCE(CAST(n AS varchar), '~'), COALESCE(CAST(amt AS varchar), '~'), COALESCE(CAST(first_t AS varchar), '~'), COALESCE(CAST(last_t AS varchar), '~'), COALESCE(CAST(first_tx AS varchar), '~'), COALESCE(CAST(fanout AS varchar), '~'), COALESCE(CAST(win_from AS varchar), '~'), COALESCE(CAST(win_cut AS varchar), '~'), COALESCE(CAST(n_key AS varchar), '~')))))) AS ck_xor,
       sum(length(concat_ws(',', CAST(chain AS varchar), CAST(kind AS varchar), CAST(mint AS varchar), CAST(from_owner AS varchar), CAST(to_owner AS varchar), CAST(n AS varchar), CAST(amt AS varchar), CAST(first_t AS varchar), CAST(last_t AS varchar), CAST(first_tx AS varchar), CAST(fanout AS varchar), CAST(win_from AS varchar), CAST(win_cut AS varchar), CAST(n_key AS varchar)))) + count(*) * 14 AS est_csv_bytes
FROM out
