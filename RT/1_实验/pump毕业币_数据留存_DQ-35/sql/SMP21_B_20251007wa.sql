      AND created_at >= TIMESTAMP '2025-10-07 00:00:00' AND created_at < TIMESTAMP '2025-10-07 03:00:00'
),
cc AS (
    /* 曲线创建事件，全历史 */
    SELECT mint, min(evt_block_time) AS curve_created_at, min_by(symbol, evt_block_time) AS symbol
    FROM pumpdotfun_solana.pump_evt_createevent
    WHERE evt_block_date BETWEEN DATE '2024-01-01' AND DATE '2025-10-13'
      AND mint IN (SELECT mint FROM cand)
