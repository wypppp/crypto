    FROM cand c
    JOIN cc s ON s.mint = c.mint
    WHERE NOT (s.curve_created_at >= TIMESTAMP '2026-06-15 00:00:00' AND s.curve_created_at < TIMESTAMP '2026-07-13 00:00:00')
