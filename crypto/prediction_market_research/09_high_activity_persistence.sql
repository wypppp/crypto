condition_resolutions AS (
    SELECT
        lower(to_hex(conditionId)) AS condition_key,
        max(evt_block_time) AS onchain_resolution_time
    FROM polymarket_polygon.ctf_evt_conditionresolution
    WHERE evt_block_date BETWEEN DATE '2026-05-01' AND DATE '2026-08-06'
    GROUP BY 1
),
md_raw AS (
    SELECT
        token_id,
        max_by(condition_id, coalesce(last_changed_at, TIMESTAMP '1970-01-01'))
            AS condition_id,
        max_by(tags, coalesce(last_changed_at, TIMESTAMP '1970-01-01')) AS tags,
        max_by(settlement_value, coalesce(last_changed_at, TIMESTAMP '1970-01-01'))
            AS settlement_value
    FROM polymarket_polygon.market_details
    GROUP BY 1
),
md AS (
    SELECT m.*, r.onchain_resolution_time
    FROM md_raw m
    LEFT JOIN condition_resolutions r
      ON r.condition_key = replace(lower(m.condition_id), '0x', '')
),
trades AS (
    SELECT
        v.maker AS wallet,
        t.horizon_time,
        v.evt_block_time,
        v.side,
        CASE WHEN v.side = 0
            THEN CAST(v.takerAmountFilled AS DOUBLE) / 1e6
            ELSE CAST(v.makerAmountFilled AS DOUBLE) / 1e6 END AS qty,
        CASE WHEN v.side = 0
            THEN CAST(v.makerAmountFilled AS DOUBLE) / 1e6
            ELSE CAST(v.takerAmountFilled AS DOUBLE) / 1e6 END AS collateral,
        CAST(v.fee AS DOUBLE) / 1e6 AS fee,
        m.tags,
        m.settlement_value,
        m.onchain_resolution_time
    FROM polymarket_v2_polygon.ctfexchange_evt_orderfilled v
    JOIN target t ON t.wallet = v.maker
    LEFT JOIN md m ON m.token_id = v.tokenId
    WHERE v.evt_block_date BETWEEN DATE '2026-05-01' AND DATE '2026-08-06'
      AND v.evt_block_time <= t.horizon_time
),
classified AS (
    SELECT
        *,
        CASE WHEN evt_block_time < horizon_time - INTERVAL '45' DAY
            THEN 'days_0_45' ELSE 'days_45_90' END AS period,
        contains(tags, 'Crypto Prices') AND contains(tags, '5M') AS is_crypto_5m,
        onchain_resolution_time IS NOT NULL
            AND onchain_resolution_time <= horizon_time AS resolved_by_horizon,
        CASE
            WHEN onchain_resolution_time IS NULL THEN 'resolution_missing'
            WHEN date_diff('second', evt_block_time, onchain_resolution_time) < 0
                THEN 'after_resolution'
            WHEN date_diff('second', evt_block_time, onchain_resolution_time) < 60
                THEN 'within_60s'
            WHEN date_diff('second', evt_block_time, onchain_resolution_time) < 300
                THEN '1_5m'
            ELSE 'gt_5m'
        END AS timing_bucket
    FROM trades
    WHERE qty > 0 AND collateral >= 0
)
SELECT
    to_hex(wallet) AS wallet,
    period,
    count(*) AS fill_events_n,
    count_if(resolved_by_horizon) AS resolved_fill_events_n,
    sum(collateral) AS collateral_turnover,
    sum(fee) AS fees,
    sum(CASE
        WHEN resolved_by_horizon AND side = 0
            THEN settlement_value * qty - collateral - fee
        WHEN resolved_by_horizon AND side = 1
            THEN collateral - settlement_value * qty - fee
        ELSE 0
    END) AS resolved_trade_pnl,
    count_if(is_crypto_5m) AS crypto_5m_fill_events_n,
    sum(CASE WHEN is_crypto_5m THEN collateral ELSE 0 END)
        AS crypto_5m_collateral_turnover,
    sum(CASE
        WHEN resolved_by_horizon AND is_crypto_5m AND side = 0
            THEN settlement_value * qty - collateral - fee
        WHEN resolved_by_horizon AND is_crypto_5m AND side = 1
            THEN collateral - settlement_value * qty - fee
        ELSE 0
    END) AS crypto_5m_resolved_trade_pnl,
    count_if(timing_bucket = 'after_resolution') AS after_resolution_fills_n,
    count_if(timing_bucket = 'within_60s') AS within_60s_fills_n,
    count_if(timing_bucket = '1_5m') AS one_to_five_min_fills_n,
    count_if(timing_bucket = 'gt_5m') AS over_five_min_fills_n
FROM classified
GROUP BY 1, 2
ORDER BY wallet, period
