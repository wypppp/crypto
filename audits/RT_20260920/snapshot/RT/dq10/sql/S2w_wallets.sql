    SELECT mint, usr, max(created_at) AS created_at, sum(IF(is_buy, sol, 0)) AS buy_sol
    FROM ew
    WHERE net_pre >= 5.3445
    GROUP BY 1, 2
    HAVING bool_or(is_buy)
),
